/* ============================================================
   نانوتراك — إطار المكان

   المشكلة التي يحلّها هذا الملفّ كلّه:

   الهاتف لا يعرف أين هو. كل مرّة تفتح فيها الكاميرا يعتبر موضعه
   الحالي هو الصفر، ويحسب اتّجاهه من بوصلة تنحرف داخل المباني
   عشرين درجة أو أربعين بسبب الحديد والكهرباء. فلو حفظتَ نقطة
   بإحداثيات الجلسة، لوجدتَها غداً في مكان آخر تماماً.

   والحلّ شريطان لاصقان على الأرض:

     الأوّل  نقطة الصفر  — عند الباب مثلاً، وهو ‎(0, 0)‎
     الثاني  الاتّجاه    — على بُعد متر أو أكثر، وهو يقول أين «قُدّام»

   منهما نبني إحداثيات تخصّ هذا المكان وحده. كل نقطة تُحفظ مسافةً
   منهما لا من الهاتف، فتعود غداً إلى موضعها بالضبط ما دام الشريطان
   في مكانهما.

   ولماذا لا تكفي البوصلة وحدها؟ لأن انحرافها ثابت تقريباً في
   الجلسة الواحدة. والمشي من الشريط الأوّل إلى الثاني يُقاس بنفس
   البوصلة المنحرفة، فحين ندوّر الإحداثيات لتصير ‎ا→ب‎ هي «قُدّام»
   يُطرح الانحراف من الطرفين ويسقط. هذه هي الفكرة كلّها: لا نُصحّح
   البوصلة، بل نبني نظاماً لا يهمّه انحرافها.
   ============================================================ */

/** أقصر قاعدة مقبولة بين الشريطين — أقلّ منها والزاوية تصير تخميناً */
export const MIN_BASE = 1;

/** القاعدة المريحة: بعدها تتحسّن الدقّة ببطء، وقبلها تسوء بسرعة */
export const GOOD_BASE = 3;

/** خطأ لصق الشريط المفترض: سنتيمترات قليلة مهما اجتهدتَ */
export const PLACEMENT = 0.04;

/**
 * يبني إطار المكان من رصدَي الشريطين.
 *
 * @param a       موضع الشريط الأوّل بإحداثيات الجلسة
 * @param b       موضع الشريط الثاني بإحداثيات الجلسة
 * @param base    طول القاعدة كما قيست يوم الإنشاء — يُمرَّر في
 *                الجلسات اللاحقة فيُصحَّح به مقياس الخطوة
 * @returns الإطار أو ‎null‎ إن كانت القاعدة أقصر من أن تُصدَّق
 */
export const makeFrame = (a, b, { base = null } = {}) => {
    const dx = b.x - a.x;
    const dz = b.z - a.z;
    const span = Math.hypot(dx, dz);

    if (!(span >= MIN_BASE)) return null;

    /*
     * الدوران يجعل المتّجه ‎ا→ب‎ هو ‎+z‎ أي «قُدّام».
     *
     * لا زوايا ولا ‎atan2‎: جيب التمام والجيب يُقرآن من المتّجه
     * مباشرةً. أرخص، وأدقّ عند الأطراف حيث تتقلّب الزوايا.
     */
    const cos = dz / span;
    const sin = dx / span;

    /*
     * تصحيح مقياس الخطوة.
     *
     * عدّاد الخطوات يفترض طول خطوتك من طولك، وهو تقريب. فلو قاست
     * الجلسة الأولى بين الشريطين ثلاثة أمتار وقاست اليوم ٢٫٧، فخطوة
     * اليوم أقصر ١٠٪ — وكل مسافة تُقاس اليوم تحتاج نفس النسبة.
     * وهذا تصحيح لا يملكه من يعتمد شريطاً واحداً.
     */
    const scale = base > 0 ? base / span : 1;

    return { ox: a.x, oz: a.z, cos, sin, span, scale, base: base > 0 ? base : span };
};

/** من إحداثيات الجلسة إلى إحداثيات المكان */
export const toVenue = (p, f) => {
    const dx = p.x - f.ox;
    const dz = p.z - f.oz;

    return {
        x: (dx * f.cos - dz * f.sin) * f.scale,
        z: (dx * f.sin + dz * f.cos) * f.scale
    };
};

/** ومن إحداثيات المكان إلى إحداثيات الجلسة — عكسها تماماً */
export const fromVenue = (p, f) => {
    const x = p.x / f.scale;
    const z = p.z / f.scale;

    return {
        x: f.ox + x * f.cos + z * f.sin,
        z: f.oz - x * f.sin + z * f.cos
    };
};

/** يحوّل خطّاً كاملاً — وهو ما يُرسم على الأرض في كل إطار */
export const pathFromVenue = (points, f) => points.map(p => {
    const at = fromVenue(p, f);
    return p.label ? { ...at, label: p.label } : at;
});

/**
 * كم درجة يخطئ الاتّجاه بسبب لصق الشريطين.
 *
 * خطأ اللصق ثابت بالسنتيمترات، والزاوية التي يُحدثها تصغر كلّما
 * طالت القاعدة. طرفان مستقلّان فالخطأ يتجمّع بجذر المجموع.
 */
export const bearingError = (span, placement = PLACEMENT) => {
    if (!(span > 0)) return 90;
    return (Math.atan2(Math.SQRT2 * placement, span) * 180) / Math.PI;
};

/**
 * وكم سنتيمتراً يعني ذلك على بُعد معيّن.
 *
 * هذا هو الرقم الذي يهمّ المستخدم فعلاً: لا «٢٫٣ درجة» بل «على بُعد
 * عشرة أمتار النقطة تزحف نصف متر». وهو ما يجعله يُبعد الشريطين.
 */
export const errorAt = (distance, span, placement = PLACEMENT) => {
    const rad = (bearingError(span, placement) * Math.PI) / 180;
    return Math.abs(distance) * Math.sin(rad) + placement;
};

/**
 * حُكم صريح على القاعدة التي اختارها المستخدم.
 *
 * ثلاث درجات لا خمس: «لا تكفي» و«مقبولة» و«جيّدة». والتدرّج الأدقّ
 * من ذلك يوهم بدقّة ليست في القياس أصلاً.
 */
export const gradeBase = (span) => {
    if (!(span >= MIN_BASE)) return 'short';
    return span >= GOOD_BASE ? 'good' : 'fair';
};

export const BASE_NOTE = {
    short: 'القاعدة أقصر من متر — الاتّجاه يصير تخميناً',
    fair: 'مقبولة — وأبعِد الشريطين أكثر لتزيد الدقّة',
    good: 'قاعدة جيّدة'
};
